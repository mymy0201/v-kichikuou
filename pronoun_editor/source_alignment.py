"""Align source-language text using unchanged executable command runs."""
from pathlib import Path
import re,json,difflib,hashlib
from core import LITERAL,parse_adv,digest

VERSION=2

def command_document(path):
    lines=path.read_text(encoding='utf-8-sig').splitlines()
    variables=path.parent/'variables.txt'
    names=variables.read_text(encoding='utf-8-sig').splitlines() if variables.exists() else []
    aliases={name.strip():f'VAR{i}' for i,name in enumerate(names) if name.strip()}
    def variables_normalized(s):
        s=re.sub(r'\b[^\W\d]\w*\b',lambda m:aliases.get(m[0],m[0]),s)
        return re.sub(r'\bVAR0*(\d+)\b',lambda m:'VAR'+str(int(m[1])),s)
    normalized=[variables_normalized(s.strip()) if not LITERAL.fullmatch(s) else '' for s in lines]
    helpers={}
    for i,s in enumerate(normalized[:-1]):
        label=re.fullmatch(r'\*(L_[0-9a-f]+):',s)
        op=re.fullmatch(r'!VAR521\s*:\s*(\d+)!',normalized[i+1])
        if label and op:helpers[label[1]]=int(op[1])
    first=min((i for i,s in enumerate(normalized) if s.startswith('*') and s[1:-1] in helpers),default=len(lines))
    commands=[];positions=[];texts=[]
    for i,s in enumerate(normalized[:first]):
        literal=LITERAL.fullmatch(lines[i])
        if literal:
            texts.append((i,literal[2]));continue
        if not s or s=='R' or re.fullmatch(r'Z[MH]\s+\d+:',s):continue
        call=re.fullmatch(r'\\(L_[0-9a-f]+):',s)
        if call and call[1] in helpers:s='WAO '+str(helpers[call[1]])
        else:
            # Labels are regenerated byte offsets in independent decompilations.
            s=re.sub(r'L_[0-9a-f]+','LABEL',s)
            # MS strings are translated UI, not executable identity.
            s=re.sub(r'^(MS\s+\d+,).*:',r'\1 TEXT:',s)
        s=re.sub(r'\s+',' ',s)
        commands.append(s);positions.append(i)
    return commands,positions,texts,first

def align(source,reference):
    left,lpos,ltext,lend=command_document(source)
    right,rpos,rtext,rend=command_document(reference)
    matcher=difflib.SequenceMatcher(None,left,right,autojunk=False)
    segments=[]
    for block in matcher.get_matching_blocks():
        if block.size<4:continue
        for offset in range(block.size-1):
            a=block.a+offset;b=block.b+offset
            segments.append((lpos[a],lpos[a+1],rpos[b],rpos[b+1],block.size))
        # File edges are valid anchors only when both streams reach that edge.
        if block.a==block.b==0:segments.append((-1,lpos[0],-1,rpos[0],block.size))
        if block.a+block.size==len(left) and block.b+block.size==len(right):segments.append((lpos[-1],lend,rpos[-1],rend,block.size))
    rows=parse_adv(source.read_bytes());result={};segments.sort();j=0
    for row in rows:
        start,end=row['indices'][0],row['indices'][-1]
        while j<len(segments) and segments[j][1]<=start:j+=1
        if j>=len(segments):break
        a,z,b,y,run=segments[j]
        if not (a<start<=end<z):continue
        original=[text for line,text in rtext if b<line<y]
        if not original:continue
        result[row['id']]={'text':' '.join(original),'scope':'command-aligned passage',
            'reference_lines':[line+1 for line,text in rtext if b<line<y],
            'matching_command_run':run,'method':'Consecutive command boundaries inside an identical normalized command run; no text/ordinal matching.'}
    return {'rows':result,'stats':{'source_rows':len(rows),'mapped_rows':len(result),'source_commands':len(left),'reference_commands':len(right)}}

def project_references(project,name,language):
    source=project.file(name)
    # This project's independently extracted and provenance-recorded originals.
    base=project.root/'editorial_review/japanese_base_20261022/reference'/language
    configured=project.config.get(language+'_source_dir')
    if configured:base=(project.root/configured).resolve()
    reference=(base/name).resolve()
    if not reference.is_relative_to(base.resolve()) or not reference.is_file():return {'rows':{},'stats':{'reason':'Original script not found'}}
    inputs=[source,reference,source.parent/'variables.txt',reference.parent/'variables.txt']
    key=digest(('v'+str(VERSION)+language+str(reference)+name+''.join(digest(p.read_bytes()) if p.exists() else '-' for p in inputs)).encode())
    cache=project.state/'reference-cache'/(key+'.json')
    if cache.exists():return json.loads(cache.read_text(encoding='utf-8'))
    result=align(source,reference)
    for row in result['rows'].values():row['source']=str(reference.relative_to(project.root)) if reference.is_relative_to(project.root) else str(reference)
    cache.parent.mkdir(parents=True,exist_ok=True)
    cache.write_text(json.dumps(result,ensure_ascii=False),encoding='utf-8')
    return result
